def analyze_export_product(image_path):
    # Load the image using PIL
    img = PIL.Image.open(image_path)

    # 2. Configure the Prompt for your SRS (US-03/US-04)
    prompt = """
    Perform an Algerian Export Compliance Audit.
    Return a JSON object with:
    - brand, product_name, net_weight
    - country_of_origin
    - compliance_status: 'NON-COMPLIANT' if origin is not 'Algeria'
    - category: 'Agro-alimentaire'
    - attributes: [usage, physical details]
    """

    try:
        # 3. Use the 2026 'Client' Syntax
        response = client.models.generate_content(
            model="gemini-3.1-flash-lite-preview",
            contents=[prompt, img]
        )

        # 4. Parse the response (Gemini 3 handles JSON-only requests natively)
        # Clean markdown if present
        raw_text = response.text.strip().replace('```json', '').replace('```', '').strip()
        return json.loads(raw_text)

    except Exception as e:
        return {"error": str(e)}

